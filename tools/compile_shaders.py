#!/usr/bin/env python3
"""Compiles the GLSL shaders to SPIR-V headers: the engine's compute shaders in
src/gpu/shaders, and the interface's view shaders in apps/tisma/shaders
(vertex and fragment, PLAN.md «Vista con Vulkan»).

glslangValidator is used only as a build tool: it is never linked into the
engine or shipped (see THIRD_PARTY.md). The generated headers are kept in the
repository so that systems without the tool can build the engine.

usage: compile_shaders.py [--check]
  --check  fail if a generated header is missing or out of date (used in CI)
"""

import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
# (folder, C++ namespace, file patterns); each folder's headers go to its generated/.
SETS = [
    (ROOT / "src" / "gpu" / "shaders", "tisma::gpu", ("*.comp",)),
    (ROOT / "apps" / "tisma" / "shaders", "tisma::ui", ("*.vert", "*.frag")),
]


def symbol(name):
    return "k" + "".join(part.capitalize() for part in name.split("_")) + "Spirv"


def compile_one(src, namespace):
    with tempfile.TemporaryDirectory() as tmp:
        spv = pathlib.Path(tmp) / "out.spv"
        subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.1", "-o", str(spv), str(src)],
                       check=True, stdout=subprocess.DEVNULL)
        data = spv.read_bytes()
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    lines = []
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) + ",")
    # A compute shader is named by its file's stem; a view shader by its
    # stem and stage (preview.vert: kPreviewVertSpirv).
    name = src.stem if src.suffix == ".comp" else src.stem + "_" + src.suffix[1:]
    return (
        f"// Generated by tools/compile_shaders.py from {src.relative_to(ROOT).as_posix()}. Do not edit.\n"
        f"#pragma once\n\n#include <cstdint>\n\nnamespace {namespace} {{\n\n"
        f"inline constexpr std::uint32_t {symbol(name)}[] = {{\n" + "\n".join(lines) + "\n};\n\n"
        f"}} // namespace {namespace}\n"
    )


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for folder, namespace, patterns in SETS:
        out_dir = folder / "generated"
        sources = sorted(src for pattern in patterns for src in folder.glob(pattern))
        for src in sources:
            text = compile_one(src, namespace)
            out = out_dir / ((src.stem if src.suffix == ".comp" else src.name) + ".spv.h")
            if check:
                if not out.exists() or out.read_text() != text:
                    stale.append(out.relative_to(ROOT))
            else:
                out_dir.mkdir(exist_ok=True)
                out.write_text(text)
                print("wrote", out.relative_to(ROOT))
    if stale:
        for s in stale:
            print("error: out of date:", s)
        print("Run tools/compile_shaders.py and commit the result.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
