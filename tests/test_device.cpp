// Waits up to `limit` for the condition; whether it came true.
template <class F>
bool within(std::chrono::milliseconds limit, F condition) {
    const auto deadline = std::chrono::steady_clock::now() + limit;
    while (!condition()) {
        if (std::chrono::steady_clock::now() > deadline)
            return false;
        std::this_thread::sleep_for(5ms);
    }
    return true;
}

// A job like the writer's: comments, blank lines, layers of moves.
std::string cube_gcode() {
    std::string g = "; generated by the tests\n\nG28\nM104 S200\nG90\nM82\n";
    for (int layer = 0; layer < 30; ++layer) {
        g += ";LAYER:" + std::to_string(layer) + "\nG1 Z" + std::to_string(layer) + ".2 F7800\n";
        for (int i = 0; i < 40; ++i)
            g += "G1 X" + std::to_string(i % 20) + " Y" + std::to_string(i / 20) + " E" + std::to_string(i) + " F1800 ; move\n";
    }
    return g + "M104 S0\nM84\n";
}

std::size_t sendable_lines(const std::string& gcode) {
    std::size_t n = 0;
    std::istringstream in(gcode);
    for (std::string line; std::getline(in, line);)
        n += !strip_gcode_line(line).empty();
    return n;
}

