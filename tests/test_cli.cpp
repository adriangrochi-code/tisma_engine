struct Run {
    int code;
    std::string out;
    std::string err;
};

Run run(std::vector<std::string> args) {
    std::vector<std::string_view> views(args.begin(), args.end());
    std::ostringstream out, err;
    const int code = run_cli(views, out, err);
    return {code, out.str(), err.str()};
}

