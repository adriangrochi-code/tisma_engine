std::vector<std::string> lines_of(const std::string& text) {
    std::vector<std::string> out;
    std::istringstream in(text);
    for (std::string line; std::getline(in, line);)
        out.push_back(line);
    return out;
}

std::string cube_gcode(const Settings& s) {
    const IndexedMesh m = weld_exact(read_stl(std::filesystem::path(TISMA_TEST_DATA_DIR) / "cube_ascii.stl").mesh);
    std::ostringstream out;
    write_gcode(out, slice_model(m, s), s);
    return out.str();
}

// A square tube 40 x 40 x 4 mm with a 20 x 20 hole in the middle.
IndexedMesh tube_mesh() {
    IndexedMesh m;
    const float outer[4][2] = {{0, 0}, {40, 0}, {40, 40}, {0, 40}};
    const float hole[4][2] = {{10, 10}, {30, 10}, {30, 30}, {10, 30}};
    for (float z : {0.0f, 4.0f}) {
        for (const auto& p : outer)
            m.vertices.push_back({p[0], p[1], z});
        for (const auto& p : hole)
            m.vertices.push_back({p[0], p[1], z});
    }
    auto quad = [&](std::uint32_t a, std::uint32_t b, std::uint32_t c, std::uint32_t d) {
        m.triangles.push_back({a, b, c});
        m.triangles.push_back({a, c, d});
    };
    for (std::uint32_t i = 0; i < 4; ++i) {
        const std::uint32_t j = (i + 1) % 4;
        quad(i, j, 8 + j, 8 + i);             // outer side, facing out
        quad(4 + j, 4 + i, 12 + i, 12 + j);   // hole side, facing into the hole
        quad(8 + i, 8 + j, 12 + j, 12 + i);   // top ring
        quad(i, 4 + i, 4 + j, j);             // bottom ring
    }
    return m;
}

// Adds a box from (x0, y0, 0) to (x1, y1, h), facing out.
void add_box(IndexedMesh& m, float x0, float y0, float x1, float y1, float h, float bottom = 0.0f) {
    const auto base = std::uint32_t(m.vertices.size());
    for (float z : {bottom, h})
        for (const auto& p : {std::array<float, 2>{x0, y0}, {x1, y0}, {x1, y1}, {x0, y1}})
            m.vertices.push_back({p[0], p[1], z});
    auto quad = [&](std::uint32_t a, std::uint32_t b, std::uint32_t c, std::uint32_t d) {
        m.triangles.push_back({base + a, base + b, base + c});
        m.triangles.push_back({base + a, base + c, base + d});
    };
    quad(0, 3, 2, 1); // bottom
    quad(4, 5, 6, 7); // top
    for (std::uint32_t i = 0; i < 4; ++i)
        quad(i, (i + 1) % 4, 4 + (i + 1) % 4, 4 + i);
}

