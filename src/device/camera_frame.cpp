std::vector<std::uint8_t> yuyv_to_rgba(std::string_view yuyv, int width, int height) {
    if (width <= 0 || height <= 0 || width % 2 != 0 ||
        yuyv.size() != static_cast<std::size_t>(width) * static_cast<std::size_t>(height) * 2)
        return {};
    std::vector<std::uint8_t> out(static_cast<std::size_t>(width) * static_cast<std::size_t>(height) * 4);
    const auto clamp = [](double v) { return static_cast<std::uint8_t>(std::clamp(v + 0.5, 0.0, 255.0)); };
    std::size_t o = 0;
    for (std::size_t i = 0; i + 3 < yuyv.size(); i += 4) {
        const double u = static_cast<unsigned char>(yuyv[i + 1]) - 128.0;
        const double v = static_cast<unsigned char>(yuyv[i + 3]) - 128.0;
        for (const std::size_t k : {i, i + 2}) {
            // BT.601: Y from 16 to 235, Cb and Cr from 16 to 240.
            const double y = 1.164 * (static_cast<unsigned char>(yuyv[k]) - 16.0);
            out[o++] = clamp(y + 1.596 * v);
            out[o++] = clamp(y - 0.392 * u - 0.813 * v);
            out[o++] = clamp(y + 2.017 * u);
            out[o++] = 255;
        }
    }
    return out;
}

