std::string mjpeg_with_huffman_tables(std::string_view frame) {
    const auto byte = [&](std::size_t i) { return static_cast<unsigned char>(frame[i]); };
    if (frame.size() < 4 || byte(0) != 0xFF || byte(1) != 0xD8)
        return std::string(frame);
    // Walk the segments up to the scan: a DHT means nothing to add.
    std::size_t at = 2;
    while (at + 4 <= frame.size()) {
        if (byte(at) != 0xFF)
            return std::string(frame); // not a marker where one should be
        const unsigned char marker = byte(at + 1);
        if (marker == 0xC4)
            return std::string(frame);
        if (marker == 0xDA) {
            std::string out(frame.substr(0, at));
            out += standard_dht();
            out += frame.substr(at);
            return out;
        }
        const std::size_t length = (static_cast<std::size_t>(byte(at + 2)) << 8) | byte(at + 3);
        if (length < 2)
            return std::string(frame);
        at += 2 + length;
    }
    return std::string(frame);
}

