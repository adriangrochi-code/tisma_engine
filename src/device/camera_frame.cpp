template <std::size_t N>
void add_table(std::string& out, std::uint8_t class_id, const std::array<std::uint8_t, 16>& bits,
               const std::array<std::uint8_t, N>& values) {
    out += static_cast<char>(class_id);
    for (const std::uint8_t b : bits)
        out += static_cast<char>(b);
    for (const std::uint8_t v : values)
        out += static_cast<char>(v);
}

std::string standard_dht() {
    std::string body;
    add_table(body, 0x00, kDcLumBits, kDcValues);
    add_table(body, 0x10, kAcLumBits, kAcLumValues);
    add_table(body, 0x01, kDcChrBits, kDcValues);
    add_table(body, 0x11, kAcChrBits, kAcChrValues);
    const std::size_t length = body.size() + 2;
    std::string out{'\xFF', '\xC4', static_cast<char>(length >> 8), static_cast<char>(length & 0xFF)};
    return out + body;
}

