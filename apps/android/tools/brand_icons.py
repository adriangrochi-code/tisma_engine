#!/usr/bin/env python3
"""Turns the interface icons of assets/brand/icons (24x24 SVG) into Android
vector drawables, app/src/main/res/drawable/tisma_*.xml.

The icons only use <path> and <circle> with fill, fill-opacity, stroke,
stroke-width, stroke-linecap and stroke-linejoin, so this handles just those
and fails on anything else. Colors are kept (the gray #808080); the app tints
them to the theme's text color.

usage: brand_icons.py [--check]
"""

import pathlib
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[3]
SRC = ROOT / "assets" / "brand" / "icons"
# The settings panel's section icons (the engine's own, named by `tisma --settings-layout`).
SECTIONS = ROOT / "assets" / "icons"
OUT = ROOT / "apps" / "android" / "app" / "src" / "main" / "res" / "drawable"
SVG = "{http://www.w3.org/2000/svg}"
CAPS = {"butt", "round", "square"}
JOINS = {"miter", "round", "bevel"}


def color(value):
    if value in (None, "none"):
        return None
    if value.startswith("#") and len(value) == 7:
        return "#FF" + value[1:].upper()
    raise ValueError("unsupported color " + value)


def convert(svg_path):
    root = ET.parse(svg_path).getroot()
    if root.get("viewBox") != "0 0 24 24":
        raise ValueError(f"{svg_path.name}: viewBox is not 0 0 24 24")
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- Generated by tools/brand_icons.py from assets/brand/icons/{svg_path.name}. Do not edit. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp" android:height="24dp"',
        '    android:viewportWidth="24" android:viewportHeight="24">',
    ]
    for el in root.iter():
        tag = el.tag.replace(SVG, "")
        if tag == "svg":
            continue
        if tag == "path":
            data = el.get("d")
        elif tag == "circle":
            cx, cy, r = (float(el.get(k)) for k in ("cx", "cy", "r"))
            data = f"M{cx - r:g},{cy:g}a{r:g},{r:g} 0 1,0 {2 * r:g},0a{r:g},{r:g} 0 1,0 {-2 * r:g},0z"
        else:
            raise ValueError(f"{svg_path.name}: unsupported element {tag}")
        attrs = [f'android:pathData="{data}"']
        fill = color(el.get("fill"))
        if fill:
            attrs.append(f'android:fillColor="{fill}"')
        if el.get("fill-opacity"):
            attrs.append(f'android:fillAlpha="{float(el.get("fill-opacity")):g}"')
        stroke = color(el.get("stroke"))
        if stroke:
            attrs.append(f'android:strokeColor="{stroke}"')
            attrs.append(f'android:strokeWidth="{float(el.get("stroke-width", "1")):g}"')
            cap, join = el.get("stroke-linecap"), el.get("stroke-linejoin")
            if cap:
                assert cap in CAPS, cap
                attrs.append(f'android:strokeLineCap="{cap}"')
            if join:
                assert join in JOINS, join
                attrs.append(f'android:strokeLineJoin="{join}"')
        lines.append("    <path " + "\n        ".join(attrs) + " />")
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv
    OUT.mkdir(parents=True, exist_ok=True)
    stale = []
    for svg in sorted(SRC.glob("tisma_*.svg")) + sorted(SECTIONS.glob("section_*.svg")):
        target = OUT / (svg.stem + ".xml")
        text = convert(svg)
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                stale.append(target.name)
        else:
            target.write_text(text, encoding="utf-8")
    if stale:
        print("out of date:", ", ".join(stale), "- run tools/brand_icons.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
